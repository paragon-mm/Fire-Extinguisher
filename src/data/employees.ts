export function findEmployeeById(empId: string): Employee | undefined {
  const cleanId = empId.trim().toLowerCase();
  if (!cleanId) return undefined;
  return EMPLOYEES.find(e => e.empId.toLowerCase() === cleanId);
}

export function searchEmployees(query: string): Employee[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  
  // Deduplicate by empId
  const map = new Map<string, Employee>();
  EMPLOYEES.forEach(e => {
    if (e.empId.toLowerCase().includes(q) || e.name.toLowerCase().includes(q)) {
      if (!map.has(e.empId)) {
        map.set(e.empId, e);
      }
    }
  });
  
  return Array.from(map.values()).slice(0, 10);
}
